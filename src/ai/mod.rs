/// Counts the characters of every tool call's serialised arguments.
///
/// A truncated response is measured by what it wrote, and a half-written tool
/// call is writing just as answer text is, so both counts are needed to tell a
/// long answer from one that never started.
///
/// Arguments are measured as the JSON text the model wrote, braces and quotes
/// included. A call with no arguments, whose input is `{}` or `null`, counts
/// as 0 rather than as the 2 or 4 characters of its JSON. Such a call costs a
/// handful of tokens, so a truncation that produced only that spent its budget
/// on reasoning, and the remedy has to say so rather than ask for less.
///
/// Arguments cut off part-way do count. A provider that sends arguments as
/// text turns a cut-off string into `null` because it does not parse, and
/// keeps the text in `unparsed_arguments`; that text is counted as written,
/// so a long but unfinished call gets the answer-length remedy.
pub(crate) fn tool_argument_chars(tool_calls: &[ToolCall]) -> usize {
    tool_calls.iter().map(written_argument_chars).sum()
}

/// Counts the characters of one call's arguments, 0 when it has none.
///
/// Text that did not parse is counted as written, without the blank space
/// around it, because it cannot be re-serialised as compact JSON.
fn written_argument_chars(call: &ToolCall) -> usize {
    if let Some(text) = &call.unparsed_arguments {
        return text.trim().chars().count();
    }
    match &call.arguments {
        serde_json::Value::Null => 0,
        serde_json::Value::Object(fields) if fields.is_empty() => 0,
        written => written.to_string().chars().count(),
    }
}

/// Says what to change when a truncated response wrote nothing at all.
///
/// Reasoning and answer draw on the same `max_tokens`, so a response that
/// stopped before writing anything spent the whole allowance reasoning. Asking
/// for a shorter answer cannot help there, because there was no answer; only
/// a larger allowance or a lower `effort` can. A response that had started
/// writing needs no remedy here, because its length is the thing to act on.
///
/// The counts are of emitted text, not of thinking: models that omit their
/// reasoning by default, Opus 5 among them, send empty thinking blocks while
/// still billing for them, so counting them would make every truncation look
/// like a long answer.
pub(crate) fn truncation_remedy(answer_chars: usize, tool_arg_chars: usize) -> &'static str {
    if answer_chars == 0 && tool_arg_chars == 0 {
        " Nothing was written, so the budget went on reasoning: raise max_tokens \
         or lower effort rather than asking for less."
    } else {
        ""
    }
}

/// A response the provider cut off at its output limit.
///
/// The request succeeded, so no provider returns this. `SessionRunner` builds
/// it from the truncated response it received, because only the session can
/// recover: the remedy is to ask the model for less, which changes the
/// request. It carries the counts of the log line in `truncation_warning`, so
/// the recovery decides from them rather than from text, and its message ends
/// with the same remedy that line gives.
#[derive(Debug, Clone, Copy, PartialEq, Eq, thiserror::Error)]
#[error(
    "LLM output was truncated by provider (e.g. hit max tokens) after {answer_chars} chars \
     of answer and {tool_arg_chars} chars of tool arguments.{}",
    truncation_remedy(*.answer_chars, *.tool_arg_chars)
)]
pub struct OutputTruncated {
    /// Characters of answer text written before the cut.
    pub answer_chars: usize,
    /// Characters of tool-call arguments written before the cut.
    pub tool_arg_chars: usize,
}

impl OutputTruncated {
    /// Measures what a truncated response wrote.
    ///
    /// Thinking is not counted, for the reason given on `truncation_remedy`.
    pub fn from_response(response: &AiResponse) -> Self {
        Self {
            answer_chars: response
                .content
                .as_deref()
                .map_or(0, |answer| answer.chars().count()),
            tool_arg_chars: tool_argument_chars(response.tool_calls.as_deref().unwrap_or_default()),
        }
    }

    /// Nothing visible was written: the budget went on reasoning.
    pub fn spent_on_reasoning(&self) -> bool {
        self.answer_chars == 0 && self.tool_arg_chars == 0
    }
}

impl ClassifyAiError for OutputTruncated {
    /// Resending the same request cannot help, because the limit has not
    /// moved. Recovery changes the request instead (see `SessionRunner`).
    fn ai_error_class(&self) -> AiErrorClass {
        AiErrorClass::Fatal
    }
}

/// Classifies a remote AI error using the typed stdio protocol payload.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "class", rename_all = "snake_case")]
pub enum AiErrorClass {
    /// The request failed permanently and should not be retried.
    Fatal,
    /// The provider is rate limited until the specified backoff expires.
    RateLimit {
        #[serde(rename = "retry_after_secs", with = "duration_secs")]
        retry_after: Duration,
    },
    /// The provider returned a transient failure that may succeed later.
    Transient {
        #[serde(rename = "retry_after_secs", with = "duration_secs")]
        retry_after: Duration,
    },
}

mod duration_secs {
    use serde::{Deserialize, Deserializer, Serializer};
    use std::time::Duration;

    pub fn serialize<S: Serializer>(duration: &Duration, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.serialize_u64(duration.as_secs())
    }

    pub fn deserialize<'de, D: Deserializer<'de>>(deserializer: D) -> Result<Duration, D::Error> {
        let secs = u64::deserialize(deserializer)?;
        Ok(Duration::from_secs(secs))
    }
}

/// Typed payload for remote AI errors sent over the stdio protocol.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
pub(crate) struct RemoteAiErrorPayload {
    pub message: String,
    #[serde(flatten)]
    pub class: AiErrorClass,
}

impl RemoteAiErrorPayload {
    #[cfg(any(feature = "server", test))]
    pub fn new(message: String, class: AiErrorClass) -> Self {
        Self { message, class }
    }

    pub fn into_error(self) -> RemoteAiError {
        RemoteAiError {
            message: self.message,
            class: self.class,
        }
    }
}

/// Error returned by a remote AI provider through the typed stdio protocol.
#[derive(Debug, Clone, thiserror::Error)]
#[error("Remote AI Error: {message}")]
pub struct RemoteAiError {
    pub message: String,
    pub class: AiErrorClass,
}

pub(crate) const DEFAULT_RETRY_AFTER: Duration = Duration::from_secs(60);

pub trait ClassifyAiError {
    fn ai_error_class(&self) -> AiErrorClass;
}

impl ClassifyAiError for RemoteAiError {
    fn ai_error_class(&self) -> AiErrorClass {
        self.class
    }
}

pub(crate) fn classify_status_code(status: reqwest::StatusCode) -> Option<AiErrorClass> {
    match status {
        reqwest::StatusCode::TOO_MANY_REQUESTS => Some(AiErrorClass::RateLimit {
            retry_after: DEFAULT_RETRY_AFTER,
        }),
        reqwest::StatusCode::INTERNAL_SERVER_ERROR
        | reqwest::StatusCode::BAD_GATEWAY
        | reqwest::StatusCode::SERVICE_UNAVAILABLE
        | reqwest::StatusCode::GATEWAY_TIMEOUT => Some(AiErrorClass::Transient {
            retry_after: DEFAULT_RETRY_AFTER,
        }),
        status if status.as_u16() == 529 => Some(AiErrorClass::Transient {
            retry_after: DEFAULT_RETRY_AFTER,
        }),
        _ => None,
    }
}

/// Classifies AI errors through typed provider and stdio error downcasts.
pub fn classify_ai_error(error: &anyhow::Error) -> AiErrorClass {
    if let Some(e) = error.downcast_ref::<RemoteAiError>() {
        return e.ai_error_class();
    }
    if let Some(e) = error.downcast_ref::<openai::OpenAiCompatError>() {
        return e.ai_error_class();
    }
    if let Some(e) = error.downcast_ref::<claude::ClaudeError>() {
        return e.ai_error_class();
    }
    if let Some(e) = error.downcast_ref::<claude_cli::ClaudeCliError>() {
        return e.ai_error_class();
    }
    if let Some(e) = error.downcast_ref::<gemini::GeminiError>() {
        return e.ai_error_class();
    }
    if let Some(e) = error.downcast_ref::<crate::worker::prompts::ReviewError>() {
        return e.ai_error_class();
    }
    if let Some(e) = error.downcast_ref::<OutputTruncated>() {
        return e.ai_error_class();
    }
    if let Some(e) = error.downcast_ref::<ollama::OllamaError>() {
        return e.ai_error_class();
    }
    if let Some(e) = error.downcast_ref::<vllm::VllmError>() {
        return e.ai_error_class();
    }
    AiErrorClass::Fatal
}

/// Token usage statistics for an AI interaction.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct AiUsage {
    /// Number of tokens in the input prompt.
    pub prompt_tokens: usize,
    /// Number of tokens in the generated completion.
    pub completion_tokens: usize,
    /// Total tokens used (prompt + completion).
    pub total_tokens: usize,
    /// Number of tokens served from cache.  A breakdown of `prompt_tokens`
    /// rather than an addend: a consumer subtracts it to get uncached input.
    /// A provider whose API reports the cached prefix outside its prompt
    /// total folds it in before filling these fields.  None when the
    /// provider reports no cache hit.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub cached_tokens: Option<usize>,
}

impl AiUsage {
    pub fn accumulate(&mut self, other: &AiUsage) {
        self.prompt_tokens += other.prompt_tokens;
        self.completion_tokens += other.completion_tokens;
        self.total_tokens += other.total_tokens;
        if let Some(other_cached) = other.cached_tokens {
            *self.cached_tokens.get_or_insert(0) += other_cached;
        }
    }
}

