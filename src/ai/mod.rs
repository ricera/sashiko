/// Recursively removes `thought_signature` and `thoughtSignature` fields from a JSON value.
pub fn scrub_thought_signatures(val: &mut serde_json::Value) {
    match val {
        serde_json::Value::Object(map) => {
            map.remove("thought_signature");
            map.remove("thoughtSignature");
            for (_, v) in map.iter_mut() {
                scrub_thought_signatures(v);
            }
        }
        serde_json::Value::Array(arr) => {
            for v in arr.iter_mut() {
                scrub_thought_signatures(v);
            }
        }
        _ => {}
    }
}

// --- Multiplexed IPC Protocol Support ---

/// The kinds of message the daemon writes to a worker's stdin.
///
/// The worker accepts only these. A line with any other `type` fails to
/// parse as an [`IpcEnvelope`], and the worker exits, because the daemon and
/// the worker are one binary and a kind one of them does not know is a
/// protocol violation rather than something to skip.
#[derive(Debug, Clone, Copy, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
#[serde(rename_all = "snake_case")]
pub(crate) enum IpcMessageType {
    /// The model's answer to the request with the same `tx_id`.
    AiResponse,
    /// The provider error that ended the request with the same `tx_id`.
    Error,
    /// The review has reached its deadline and should wind down: the stages
    /// that gather concerns stop, and the ones that turn concerns into
    /// findings finish. Answers no request, so its `tx_id` is 0, which the
    /// registry never issues.
    WindDown,
}

#[derive(Debug, serde::Serialize, serde::Deserialize)]
pub(crate) struct IpcEnvelope {
    #[serde(rename = "type")]
    pub msg_type: IpcMessageType,
    pub tx_id: u64,
    pub payload: serde_json::Value,
}

impl IpcEnvelope {
    /// Builds the newline-terminated stdin line for one daemon-to-worker
    /// message.
    ///
    /// The daemon writes every reply through this, so the writer and the
    /// worker's reader share one envelope type and one spelling of each kind.
    #[cfg(any(feature = "server", test))]
    pub(crate) fn line(
        msg_type: IpcMessageType,
        tx_id: u64,
        payload: &impl Serialize,
    ) -> serde_json::Result<String> {
        let envelope = IpcEnvelope {
            msg_type,
            tx_id,
            payload: serde_json::to_value(payload)?,
        };
        let mut line = serde_json::to_string(&envelope)?;
        line.push('\n');
        Ok(line)
    }
}

/// The reply one stdin line carries: its `tx_id` and the result to dispatch.
type IpcReply = (u64, Result<AiResponse, RemoteAiError>);

/// What one stdin line asks the worker to do.
#[derive(Debug)]
enum IpcInbound {
    /// Hand a reply to the request it answers.
    Reply(IpcReply),
    /// Set the worker's wind-down signal.
    WindDown,
}

/// Reads one line from the worker's stdin into what it asks for.
///
/// An `Err` is a protocol violation, described for the log. It is returned
/// rather than acted on so that the parsing can be tested without ending the
/// test process.
fn parse_ipc_message(line: &str) -> Result<IpcInbound, String> {
    let envelope = serde_json::from_str::<IpcEnvelope>(line)
        .map_err(|e| format!("Received a malformed message on stdin ({}): {}", e, line))?;
    let tx_id = envelope.tx_id;
    let result = match envelope.msg_type {
        IpcMessageType::AiResponse => {
            let response =
                serde_json::from_value::<AiResponse>(envelope.payload).map_err(|_| {
                    format!("Failed to parse payload as AiResponse for tx_id {}", tx_id)
                })?;
            Ok(response)
        }
        IpcMessageType::Error => {
            let payload = serde_json::from_value::<RemoteAiErrorPayload>(envelope.payload)
                .map_err(|_| {
                    format!(
                        "Failed to parse payload as RemoteAiErrorPayload for tx_id {}",
                        tx_id
                    )
                })?;
            Err(payload.into_error())
        }
        IpcMessageType::WindDown => return Ok(IpcInbound::WindDown),
    };
    Ok(IpcInbound::Reply((tx_id, result)))
}

/// Acts on one stdin line: dispatches a reply, or sets the wind-down signal.
///
/// Apart from the reader so a test can drive it with its own registry and
/// signal. The process-wide signal is shared by every test in the binary, so
/// setting it there would wind down unrelated tests.
async fn handle_ipc_line(
    registry: &IpcRegistry,
    wind_down: &WindDownSignal,
    line: &str,
) -> Result<(), String> {
    match parse_ipc_message(line)? {
        IpcInbound::Reply((tx_id, result)) => registry.dispatch(tx_id, result).await,
        IpcInbound::WindDown => {
            tracing::info!(
                "The review reached its deadline: stopping the analysis stages and \
                 finishing the consolidation stages"
            );
            wind_down.request();
        }
    }
    Ok(())
}

/// Tells a worker's review that it has reached its deadline.
///
/// Set by the stdin reader when the daemon sends
/// [`IpcMessageType::WindDown`], and read by every session at its turn
/// boundaries. It is a plain flag rather than a cancellation token because
/// the worker build has no `tokio-util`, and nothing waits on it: a session
/// only asks, between turns, whether it is set. It is never cleared, because
/// a worker reviews exactly one patch per spawn.
#[derive(Debug, Default)]
pub struct WindDownSignal(std::sync::atomic::AtomicBool);

impl WindDownSignal {
    /// Asks every session that reads this signal to wind down.
    pub fn request(&self) {
        self.0.store(true, std::sync::atomic::Ordering::SeqCst);
    }

    /// Whether the review has been asked to wind down.
    pub fn is_requested(&self) -> bool {
        self.0.load(std::sync::atomic::Ordering::SeqCst)
    }
}

pub(crate) struct IpcRegistry {
    next_tx_id: std::sync::atomic::AtomicU64,
    // Set by abort_all() when the reader stops.  Both the store and the load
    // in register() happen under the pending lock, so a registration racing
    // the shutdown either lands before the drain and is aborted by it, or
    // observes the flag and fails instead of waiting for a reply that can no
    // longer arrive.
    closed: std::sync::atomic::AtomicBool,
    pending: tokio::sync::Mutex<
        std::collections::HashMap<
            u64,
            tokio::sync::oneshot::Sender<Result<AiResponse, RemoteAiError>>,
        >,
    >,
}

impl IpcRegistry {
    pub fn new() -> Self {
        Self {
            next_tx_id: std::sync::atomic::AtomicU64::new(1),
            closed: std::sync::atomic::AtomicBool::new(false),
            pending: tokio::sync::Mutex::new(std::collections::HashMap::new()),
        }
    }

    /// Advisory check for callers that want to skip work on a dead channel.
    /// register() makes the authoritative decision under the pending lock.
    pub fn is_closed(&self) -> bool {
        self.closed.load(std::sync::atomic::Ordering::SeqCst)
    }

    pub fn next_id(&self) -> u64 {
        self.next_tx_id
            .fetch_add(1, std::sync::atomic::Ordering::SeqCst)
    }

    pub async fn register(
        &self,
        tx_id: u64,
        tx: tokio::sync::oneshot::Sender<Result<AiResponse, RemoteAiError>>,
    ) -> Result<(), RemoteAiError> {
        let mut map = self.pending.lock().await;
        if self.closed.load(std::sync::atomic::Ordering::SeqCst) {
            return Err(RemoteAiError {
                message: "IPC channel disconnected (stdin closed)".to_string(),
                class: AiErrorClass::Fatal,
            });
        }
        if map.insert(tx_id, tx).is_some() {
            eprintln!(
                "CRITICAL PROTOCOL ERROR: Duplicate transaction ID {} registered!",
                tx_id
            );
            std::process::exit(1);
        }
        Ok(())
    }

    pub async fn dispatch(&self, tx_id: u64, result: Result<AiResponse, RemoteAiError>) {
        let mut map = self.pending.lock().await;
        if let Some(sender) = map.remove(&tx_id) {
            let _ = sender.send(result);
        } else {
            eprintln!(
                "CRITICAL PROTOCOL ERROR: Unsolicited response received for tx_id: {}!",
                tx_id
            );
            std::process::exit(1);
        }
    }

    pub async fn abort_all(&self, err: RemoteAiError) {
        let mut map = self.pending.lock().await;
        self.closed.store(true, std::sync::atomic::Ordering::SeqCst);
        for (_tx_id, sender) in map.drain() {
            let _ = sender.send(Err(err.clone()));
        }
    }
}

impl Default for IpcRegistry {
    fn default() -> Self {
        Self::new()
    }
}

pub(crate) struct AtomicWriter {
    writer: tokio::sync::Mutex<tokio::io::Stdout>,
}

impl AtomicWriter {
    pub fn new() -> Self {
        Self {
            writer: tokio::sync::Mutex::new(tokio::io::stdout()),
        }
    }

    pub async fn write_line(&self, line: &str) -> Result<()> {
        use tokio::io::AsyncWriteExt;
        let mut lock = self.writer.lock().await;
        lock.write_all(line.as_bytes()).await?;
        lock.write_all(b"\n").await?;
        lock.flush().await?;
        Ok(())
    }
}

impl Default for AtomicWriter {
    fn default() -> Self {
        Self::new()
    }
}

// Concurrent reviews each build a fresh provider.  A registry per provider
// would restart tx_ids at 1 and add a second reader on the shared stdin, so
// a response could land in a registry that never issued that id.
static IPC_REGISTRY: std::sync::OnceLock<Arc<IpcRegistry>> = std::sync::OnceLock::new();
static IPC_WRITER: std::sync::OnceLock<Arc<AtomicWriter>> = std::sync::OnceLock::new();
// One per process, like the registry: the stdin reader that sets it is shared
// by every review the process runs.
static WIND_DOWN: std::sync::OnceLock<Arc<WindDownSignal>> = std::sync::OnceLock::new();
// Holding the join handle rather than a "started" flag lets
// ensure_stdin_reader() tell a running reader from one that has stopped --
// stdin EOF, a read error, or the runtime it was spawned on being dropped --
// and replace it, so a later request never waits on a reply that nothing is
// left to deliver.
static IPC_READER: std::sync::Mutex<Option<tokio::task::JoinHandle<()>>> =
    std::sync::Mutex::new(None);

pub(crate) fn ipc_registry() -> Arc<IpcRegistry> {
    IPC_REGISTRY
        .get_or_init(|| Arc::new(IpcRegistry::new()))
        .clone()
}

/// The signal the stdin reader sets when the daemon sends `wind_down`.
///
/// Only a daemon-spawned worker hands it to its review: nothing else has a
/// daemon on stdin to send one.
pub fn wind_down_signal() -> Arc<WindDownSignal> {
    WIND_DOWN
        .get_or_init(|| Arc::new(WindDownSignal::default()))
        .clone()
}

pub(crate) fn ipc_writer() -> Arc<AtomicWriter> {
    IPC_WRITER
        .get_or_init(|| Arc::new(AtomicWriter::new()))
        .clone()
}

/// Spawns the stdin reader unless one is already running on this runtime.
pub(crate) fn ensure_stdin_reader() {
    let registry = ipc_registry();

    // Once the channel has closed it stays closed, so a replacement reader
    // would do nothing but hit EOF again.  register() reports the failure.
    if registry.is_closed() {
        return;
    }

    let mut reader = IPC_READER.lock().unwrap();
    if matches!(reader.as_ref(), Some(handle) if !handle.is_finished()) {
        return;
    }
    *reader = Some(start_stdin_reader(registry, wind_down_signal()));
}

pub(crate) fn start_stdin_reader(
    registry: Arc<IpcRegistry>,
    wind_down: Arc<WindDownSignal>,
) -> tokio::task::JoinHandle<()> {
    tokio::spawn(async move {
        use tokio::io::{AsyncBufReadExt, BufReader};
        let stdin = tokio::io::stdin();
        let reader = BufReader::new(stdin);
        let mut lines = reader.lines();

        while let Ok(Some(line)) = lines.next_line().await {
            if let Err(violation) = handle_ipc_line(&registry, &wind_down, &line).await {
                eprintln!("CRITICAL PROTOCOL ERROR: {}", violation);
                std::process::exit(1);
            }
        }

        registry
            .abort_all(RemoteAiError {
                message: "IPC channel disconnected (stdin closed)".to_string(),
                class: AiErrorClass::Fatal,
            })
            .await;
    })
}

