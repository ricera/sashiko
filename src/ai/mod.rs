/// Represents the role of a message in an AI conversation.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "lowercase")]
pub enum AiRole {
    /// System instruction that sets the behavior or context of the AI.
    System,
    /// Message from the end user.
    User,
    /// Message generated by the AI assistant.
    Assistant,
    /// Message containing the result of a tool execution.
    Tool,
}

/// A single message in an AI conversation.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct AiMessage {
    /// The role of the message sender.
    pub role: AiRole,
    /// The optional text content of the message.
    pub content: Option<String>,
    /// Optional thoughts of the AI model.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub thought: Option<String>,
    /// Optional thoughts signature of the AI model.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub thought_signature: Option<String>,
    /// Optional tool calls requested by the AI (usually only for Assistant role).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tool_calls: Option<Vec<ToolCall>>,
    /// Optional ID matching a tool call (required for Tool role).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tool_call_id: Option<String>,
}

/// Represents a request from the AI to call a specific tool/function.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct ToolCall {
    /// Unique identifier for this tool call.
    pub id: String,
    /// Name of the function to be called.
    pub function_name: String,
    /// Arguments for the function call as a JSON object.
    pub arguments: serde_json::Value,
    /// Optional thought signature from the AI model (required by some providers like Gemini).
    #[serde(skip_serializing_if = "Option::is_none")]
    pub thought_signature: Option<String>,
    /// The arguments text exactly as the model wrote it, kept only when it
    /// did not parse as JSON, in which case `arguments` is `null`.
    ///
    /// Providers that send arguments as a string, such as OpenAI-compatible
    /// endpoints and vLLM, send a cut-off string when the response stops at
    /// the output limit part-way through a call. `null` alone would then read
    /// as a call with no input, so the text is kept to show that the model
    /// was writing (see `tool_argument_chars`), and the conversation log
    /// shows what was cut.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub unparsed_arguments: Option<String>,
}

impl ToolCall {
    /// Builds a call from arguments the provider sent as JSON text.
    ///
    /// Blank text is a call with no input, so it becomes `null` with nothing
    /// kept. Text that does not parse also becomes `null`, as the tools have
    /// always received it, but is kept in `unparsed_arguments`, because on a
    /// truncated response it is the start of arguments the model was writing.
    pub(crate) fn from_argument_text(id: String, function_name: String, text: &str) -> Self {
        let (arguments, unparsed_arguments) = if text.trim().is_empty() {
            (serde_json::Value::Null, None)
        } else {
            match serde_json::from_str(text) {
                Ok(arguments) => (arguments, None),
                Err(_) => (serde_json::Value::Null, Some(text.to_string())),
            }
        };
        Self {
            id,
            function_name,
            arguments,
            thought_signature: None,
            unparsed_arguments,
        }
    }
}

/// Definition of the expected response format from the AI.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "lowercase")]
pub enum AiResponseFormat {
    /// Standard text response.
    Text,
    /// JSON response with optional schema.
    Json {
        /// Optional JSON Schema defining the expected structure.
        #[serde(skip_serializing_if = "Option::is_none")]
        schema: Option<serde_json::Value>,
    },
}

impl AiResponseFormat {
    /// Returns a strict instruction string to enforce JSON output for the given format.
    pub fn format_json_schema_instruction(&self) -> Option<String> {
        match self {
            AiResponseFormat::Json {
                schema: Some(schema),
            } => {
                if let Ok(schema_str) = serde_json::to_string(schema) {
                    Some(format!(
                        "RESPONSE FORMAT: You MUST respond with ONLY a valid JSON object matching this schema: {schema_str}. \
                         Do not include any explanation, markdown, or code fences — output raw JSON."
                    ))
                } else {
                    Some(
                        "RESPONSE FORMAT: You MUST respond with ONLY a valid JSON object. \
                         Do not include any explanation, markdown, or code fences — output raw JSON."
                            .to_string(),
                    )
                }
            }
            AiResponseFormat::Json { schema: None } => Some(
                "RESPONSE FORMAT: You MUST respond with ONLY a valid JSON object. \
                     Do not include any explanation, markdown, or code fences — output raw JSON."
                    .to_string(),
            ),
            AiResponseFormat::Text => None,
        }
    }
}

